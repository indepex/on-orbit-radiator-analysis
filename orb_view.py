#!/usr/bin/env python3
"""
Create plots, xlsx, and optional 3D visualization from attitude npz.

Usage:
  orb_view.py <attitude.npz> [-x] (-f | -v) [-n <name>] [-d <dir>] [-m <model>]

Options:
  <attitude.npz>    NPZ file generated by orb_att.py
  -x                Export an Excel (XLSX) workbook
  -f                Generate angle plots
  -v                Generate a PyVista visualization
  -m <mod>          Satellite geometry model required for -v; use arrow for an axes-only model
  -n <name>         Prefix for output filenames
  -d <dir>          Output directory
"""
from docopt import docopt, DocoptExit
import numpy as np
from astropy.time import Time

from lib_view import view_sat
from lib_plot import plot_angle, output_xlsx
from lib_utils import jd2iso


def main(args):
    # Validate command-line options.
    if not args['-x'] and not args['-f'] and not args['-v']:
        print('Select at least one of x,f,v')
        raise DocoptExit()
    if args['-v'] and args['-m'] is None:
        print('v requires model')
        raise DocoptExit()
    if args['-d'] is not None and args['-n'] is None:
        print('d requires name')
        raise DocoptExit()
    if args['-x'] and args['-d'] is None:
        print('x requires dir')
        raise DocoptExit()

    # Load the orbit and attitude calculation results.
    data = np.load(args['<attitude.npz>'])
    n = int(data["ncase"])

    for k in range(n):
        p = f"case{k:03d}"
        # Assemble the inputs for the plotting and visualization functions.
        case = {
            # Orbit parameters
            "altitude": float(data[f"{p}_altitude"]),
            "ltan": float(data[f"{p}_ltan"]),
            "Torb": float(data[f"{p}_Torb"]),
            # Observation target
            "target": data[f"{p}_target_name"],
            "toObj": data[f"{p}_toObj"],
            # Observation parameters
            "year": int(data[f"{p}_year"]),
            "sun_longitude": float(data[f"{p}_sun_longitude"]),
            "target_pa": float(data[f"{p}_target_pa"]),
            "roll_angle": float(data[f"{p}_roll_angle"]),
            "jdc": Time(float(data[f"{p}_jdc_jd"]), format='jd'),
            "jdciso": jd2iso(Time(float(data[f"{p}_jdc_jd"]), format='jd')),
            # Samples along one orbit
            "theta": data[f"{p}_theta"],
            "toSat": data[f"{p}_toSat"],
            "toSun": data[f"{p}_toSun"],
            "SatX": data[f"{p}_SatX"],
            "SatY": data[f"{p}_SatY"],
            "SatZ": data[f"{p}_SatZ"]
        }
        if args['-v']:
            if args['-d']:
                view_file = f"{args['-d']}/{args['-n']}_view{k:02d}.png"
                html_file = f"{args['-d']}/{args['-n']}_view{k:02d}.html"
                print(view_file, args['-m'])
            else:
                view_file, html_file = None, None
            view_sat(case, args['-m'], view_file, html_file)
        if args['-f']:
            if args['-d']:
                plot_file = f"{args['-d']}/{args['-n']}_plot{k:02d}.pdf"
            else:
                plot_file, html_file = None, None
            plot_angle(case, plot_file)
        if args['-x'] and args['-d']:
            xlsx_file = f"{args['-d']}/{args['-n']}_attitude.xlsx"
            output_xlsx(case, xlsx_file, (True if k == 0 else False))


if __name__ == "__main__":
    args = docopt(__doc__)
    main(args)
